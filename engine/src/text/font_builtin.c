/* clang-format on */

void rb_font_builtin_source(
    rb_font_source *source,
    u8              coverage[RB_FONT_GLYPH_COUNT][RB_FONT_BUILTIN_CELL * RB_FONT_BUILTIN_CELL]) {
    const f32 cell = (f32)RB_FONT_BUILTIN_CELL;
    for (u32 g = 0; g < RB_FONT_GLYPH_COUNT; ++g) {
        bool ink = false;
        for (u32 row = 0; row < RB_FONT_BUILTIN_CELL; ++row) {
            for (u32 col = 0; col < RB_FONT_BUILTIN_CELL; ++col) {
                bool covered = rb_font_builtin_glyphs[g][row][col] == '#';
                coverage[g][row * RB_FONT_BUILTIN_CELL + col] = covered ? 255 : 0;
                ink = ink || covered;
            }
        }
        /* Nothing to see (the space): no image, no room in the atlas, no quad to draw. */
        source->images[g] =
            ink ? (rb_glyph_image){RB_FONT_BUILTIN_CELL, RB_FONT_BUILTIN_CELL, coverage[g]}
                : (rb_glyph_image){0};
        /* The cell's top-left corner sits `ascent` above the pen on the baseline. */
        source->glyphs[g] = (rb_glyph){.offset = {0.0f, -BUILTIN_ASCENT}, .advance = cell};
    }
    source->metrics = (rb_font_metrics){BUILTIN_ASCENT, BUILTIN_DESCENT, BUILTIN_LINE_GAP};
    source->atlas_width = BUILTIN_ATLAS_WIDTH;
    source->filter = RB_TEXTURE_FILTER_NEAREST;
}
